/**
 * Logs in via gaia and returns the JWT, or null if rejected.
 */
export async function loginViaGaia(username: string, password: string): Promise<string | null> {
  const res = await executeDocument<{
    gaiaMutations: { login: { token: string } | null };
  }>(LoginDocument, { input: { username, password } });
  if (!res.success || !res.data) {
    return null;
  }
  return res.data.gaiaMutations.login?.token ?? null;
}

/**
 * Reports whether a status code is worth retrying.
 *
 * @param status the HTTP status, or undefined
 * @returns true for server errors and rate limiting
 */
function isTransientStatus(status: number | undefined): boolean {
  return status !== undefined && (status >= 500 || status === 429 || status === 408);
}

/**
 * Returns the logged-in reader account for a JWT, or null. Cached briefly by
 * token so concurrent requests share one backend lookup.
 *
 * @param token The JWT from the auth cookie.
 * @returns The reader account, or null.
 */
export async function getCurrentUser(token: string | undefined): Promise<ReaderAccount | null> {
  if (!token) {
    return null;
  }
  return sharedCall(`user:${token}`, CURRENT_USER_TTL_MS, () => loadCurrentUser(token));
}

/**
 * Fetches the reader account for a JWT.
 * Throws on transient backend errors so the caller can keep the cookie.
 * For password-registered HUMAN accounts without a hades row, returns a
 * synthetic ReaderAccount so the session stays alive with limited UI.
 *
 * @param token The JWT.
 * @returns The reader account, or null.
 */
async function loadCurrentUser(token: string): Promise<ReaderAccount | null> {
  const res = await executeDocument<CurrentUserQuery>(CurrentUserDocument, {}, token);
  if (!res.success) {
    if (isTransientStatus(res.statusCode)) {
      throw new Error(res.error || "Transient auth error");
    }
    return null;
  }
  const me = res.data?.gaiaQueries.me;
  if (!me) {
    return null;
  }
  if (res.data?.hadesQueries.readerAccount) {
    return res.data.hadesQueries.readerAccount;
  }
  return {
    id: me.id,
    gaiaAccountId: me.id,
    discordId: "",
    discordUsername: me.username,
    globalName: me.username,
    avatar: null,
    cefrLevel: null,
    guildRoles: [],
    createdAt: me.createdAt ?? null,
    updatedAt: me.updatedAt ?? null,
  } as unknown as ReaderAccount;
}

/**
 * Revokes the current JWT server-side (best-effort).
 */
export async function logoutViaBackend(token: string | undefined): Promise<void> {
  if (!token) return;
  try {
    await executeDocument(LogoutDocument, {}, token);
  } catch (_) {
    // best-effort: cookie will be cleared anyway
  }
}

/**
 * Result of a Discord code exchange.
 */
export type DiscordLoginResult =
  | {
      /**
       * Login succeeded; the JWT to store.
       */
      status: "ok";
      token: string;
    }
  | {
      /**
       * The account exists but is deactivated; a reactivation email is needed.
       */
      status: "deactivated";
    };

/**
 * Exchanges a Discord code for a JWT, or null on failure.
 */
export async function discordLoginViaCode(
  code: string,
  state: string,
): Promise<DiscordLoginResult | null> {
  const res = await executeDocument<DiscordLoginMutation>(DiscordLoginDocument, { code, state });
  if (!res.success || !res.data) {
    return null;
  }
  const login = res.data.hadesMutations.discordLogin;
  if (!login) {
    return null;
  }
  if (login.requiresReactivation) {
    return { status: "deactivated" };
  }
  return { status: "ok", token: login.token };
}
